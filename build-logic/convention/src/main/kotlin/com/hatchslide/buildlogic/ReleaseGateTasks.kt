private const val BUNDLETOOL_MAIN = "com.android.tools.build.bundletool.BundleToolMain"

/** Builds the full APK set of a bundle with bundletool (every split, signed with the debug key). */
abstract class ApkSetTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val bundle: RegularFileProperty

    @get:Classpath
    abstract val bundletool: ConfigurableFileCollection

    /** The SDK's aapt2: the Maven bundletool artifact does not embed one. */
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val aapt2: RegularFileProperty

    @get:OutputFile
    abstract val apks: RegularFileProperty

    @get:Inject
    abstract val exec: ExecOperations

    @TaskAction
    fun build() {
        exec.javaexec {
            classpath = bundletool
            mainClass.set(BUNDLETOOL_MAIN)
            args(
                "build-apks",
                "--bundle=${bundle.get().asFile}",
                "--output=${apks.get().asFile}",
                "--aapt2=${aapt2.get().asFile}",
                "--overwrite",
            )
        }
    }
}

/**
 * Per-device download size (spec section 8): `bundletool get-size total` for each device spec, written
 * to SIZE_REPORT.md with the asset manifest's breakdown. Fails when a device falls outside
 * [minMegabytes]..[maxMegabytes] (1 MB = 1,000,000 bytes, as Play reports sizes).
 */
abstract class SizeReportTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val apks: RegularFileProperty

    @get:Classpath
    abstract val bundletool: ConfigurableFileCollection

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NAME_ONLY)
    abstract val deviceSpecs: ConfigurableFileCollection

    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val assetManifest: RegularFileProperty

    @get:Input
    abstract val minMegabytes: Property<Int>

    @get:Input
    abstract val maxMegabytes: Property<Int>

    @get:OutputFile
    abstract val report: RegularFileProperty

    @get:Inject
    abstract val exec: ExecOperations

    @TaskAction
    fun measure() {
        val rows = deviceSpecs.files.sortedBy { it.name }.map { spec ->
            val out = ByteArrayOutputStream()
            exec.javaexec {
                classpath = bundletool
                mainClass.set(BUNDLETOOL_MAIN)
                args("get-size", "total", "--apks=${apks.get().asFile}", "--device-spec=$spec")
                standardOutput = out
            }
            // Output: a "MIN,MAX" header and one line of byte counts.
            val values = out.toString().trim().lines().last().split(",").map { it.trim().toLong() }
            spec.nameWithoutExtension to values.max()
        }
        val failures = rows.filter { (_, bytes) -> bytes / 1e6 < minMegabytes.get() || bytes / 1e6 > maxMegabytes.get() }
        report.get().asFile.writeText(markdown(rows))
        if (failures.isNotEmpty()) {
            throw GradleException(
                "Download size outside ${minMegabytes.get()}..${maxMegabytes.get()} MB: " +
                    failures.joinToString { "${it.first} ${"%.1f".format(it.second / 1e6)} MB" },
            )
        }
        logger.lifecycle("Size report: " + rows.joinToString { "${it.first} ${"%.1f".format(it.second / 1e6)} MB" })
    }

    private fun markdown(rows: List<Pair<String, Long>>): String = buildString {
        appendLine("# Size report")
        appendLine()
        appendLine("Generated by `./gradlew :app:sizeReport` from the release bundle with `bundletool get-size total`.")
        appendLine("Download sizes are what Google Play sends to each device: the base module, its configuration")
        appendLine("splits (one ABI, one density, one texture format) and the install-time `hd_assets` pack.")
        appendLine("The gate requires every device to download between ${minMegabytes.get()} and ${maxMegabytes.get()} MB")
        appendLine("(1 MB = 1,000,000 bytes).")
        appendLine()
        appendLine("| Device spec | Download |")
        appendLine("| --- | --- |")
        for ((name, bytes) in rows) appendLine("| `$name` | ${"%.1f".format(bytes / 1e6)} MB |")
        appendLine()
        appendLine("## Generated assets (uncompressed, from `assets_manifest.json`)")
        appendLine()
        appendLine("Textures are shipped in two compression formats; each device downloads one of them.")
        appendLine()
        appendLine("| Category | Size |")
        appendLine("| --- | --- |")
        for ((category, bytes) in manifestCategories()) appendLine("| $category | ${"%.1f".format(bytes / 1e6)} MB |")
    }

    /** Category totals from the manifest's `bytesByCategory` object (flat JSON, read without a parser). */
    private fun manifestCategories(): List<Pair<String, Long>> {
        val text = assetManifest.get().asFile.readText()
        val block = text.substringAfter("\"bytesByCategory\"").substringAfter("{").substringBefore("}")
        return Regex("\"([^\"]+)\"\\s*:\\s*(\\d+)").findAll(block).map { it.groupValues[1] to it.groupValues[2].toLong() }.toList()
    }
}

/**
 * 16 KB page-size support (spec section 10): every arm64-v8a and x86_64 native library has LOAD
 * segments aligned to at least 16 KB, and is stored uncompressed at a 16 KB boundary in every APK
 * that carries it (checked directly and, when the SDK has it, with `zipalign -c -P 16`).
 */
abstract class Verify16KbAlignmentTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val bundle: RegularFileProperty

    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val apks: RegularFileProperty

    @get:InputFile
    @get:Optional
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val zipalign: RegularFileProperty

    @get:OutputFile
    abstract val report: RegularFileProperty

    @get:Inject
    abstract val exec: ExecOperations

    @TaskAction
    fun verify() {
        val problems = mutableListOf<String>()
        val checked = mutableListOf<String>()
        ZipFile(bundle.get().asFile).use { zip ->
            for (entry in zip.entries().asSequence().filter { isLibrary64(it.name) }) {
                val align = loadAlignments(zip.getInputStream(entry).readBytes())
                checked += "${entry.name}: LOAD alignment ${align.joinToString()}"
                if (align.isEmpty() || align.any { it < PAGE }) problems += "${entry.name}: LOAD segments aligned to ${align.joinToString()}"
            }
        }
        val workDir = temporaryDir.apply { deleteRecursively() }.also { it.mkdirs() }
        ZipFile(apks.get().asFile).use { set ->
            for (entry in set.entries().asSequence().filter { it.name.endsWith(".apk") }) {
                val apk = File(workDir, entry.name.replace('/', '_'))
                set.getInputStream(entry).use { input -> apk.outputStream().use { input.copyTo(it) } }
                val libraries = libraryOffsets(apk)
                if (libraries.isEmpty()) continue
                for ((name, offset, stored) in libraries) {
                    checked += "${entry.name}!$name: stored=$stored offset=$offset"
                    if (!stored) problems += "${entry.name}!$name is compressed"
                    if (offset % PAGE != 0L) problems += "${entry.name}!$name starts at $offset, not a 16 KB boundary"
                }
                val tool = zipalign.orNull?.asFile
                if (tool != null && tool.canExecute()) {
                    val result = exec.exec {
                        commandLine(tool.absolutePath, "-c", "-P", "16", "4", apk.absolutePath)
                        isIgnoreExitValue = true
                        standardOutput = ByteArrayOutputStream()
                    }
                    if (result.exitValue != 0) problems += "zipalign -c -P 16 failed for ${entry.name}"
                }
            }
        }
        report.get().asFile.writeText((checked + problems.map { "PROBLEM: $it" }).joinToString("\n") + "\n")
        if (problems.isNotEmpty()) throw GradleException("16 KB alignment:\n" + problems.joinToString("\n"))
        logger.lifecycle("16 KB alignment: ${checked.size} libraries and APK entries checked")
    }

    private fun isLibrary64(name: String) = name.endsWith(".so") && ("/arm64-v8a/" in name || "/x86_64/" in name)

    /** p_align of every PT_LOAD program header of a 64-bit little-endian ELF file. */
    private fun loadAlignments(elf: ByteArray): List<Long> {
        val b = ByteBuffer.wrap(elf).order(ByteOrder.LITTLE_ENDIAN)
        if (elf.size < 64 || b.getInt(0) != 0x464C457F || elf[4].toInt() != 2) return emptyList()
        val phoff = b.getLong(0x20).toInt()
        val phentsize = b.getShort(0x36).toInt()
        val phnum = b.getShort(0x38).toInt()
        return (0 until phnum).mapNotNull { i ->
            val at = phoff + i * phentsize
            if (b.getInt(at) == PT_LOAD) b.getLong(at + 0x30) else null
        }
    }

    /** Native-library entries of an APK: name, data offset and whether they are stored uncompressed. */
    private fun libraryOffsets(apk: File): List<Triple<String, Long, Boolean>> = RandomAccessFile(apk, "r").use { file ->
        val length = file.length()
        // End of central directory: the last record with the 0x06054b50 signature.
        val tail = ByteArray(minOf(length, 65_557L).toInt())
        file.seek(length - tail.size)
        file.readFully(tail)
        val t = ByteBuffer.wrap(tail).order(ByteOrder.LITTLE_ENDIAN)
        val eocd = (tail.size - 22 downTo 0).first { t.getInt(it) == 0x06054b50 }
        val entries = t.getShort(eocd + 10).toInt() and 0xFFFF
        val cdSize = t.getInt(eocd + 12).toLong() and 0xFFFFFFFFL
        val cdOffset = t.getInt(eocd + 16).toLong() and 0xFFFFFFFFL
        val cd = ByteArray(cdSize.toInt())
        file.seek(cdOffset)
        file.readFully(cd)
        val c = ByteBuffer.wrap(cd).order(ByteOrder.LITTLE_ENDIAN)
        var p = 0
        val result = mutableListOf<Triple<String, Long, Boolean>>()
        repeat(entries) {
            val method = c.getShort(p + 10).toInt()
            val nameLength = c.getShort(p + 28).toInt() and 0xFFFF
            val extraLength = c.getShort(p + 30).toInt() and 0xFFFF
            val commentLength = c.getShort(p + 32).toInt() and 0xFFFF
            val localOffset = c.getInt(p + 42).toLong() and 0xFFFFFFFFL
            val name = String(cd, p + 46, nameLength)
            if (isLibrary64("/$name")) {
                val local = ByteArray(30)
                file.seek(localOffset)
                file.readFully(local)
                val l = ByteBuffer.wrap(local).order(ByteOrder.LITTLE_ENDIAN)
                val dataOffset = localOffset + 30 + (l.getShort(26).toInt() and 0xFFFF) + (l.getShort(28).toInt() and 0xFFFF)
                result += Triple(name, dataOffset, method == 0)
            }
            p += 46 + nameLength + extraLength + commentLength
        }
        result
    }

    private companion object {
        const val PAGE = 16_384L
        const val PT_LOAD = 1
    }
}
